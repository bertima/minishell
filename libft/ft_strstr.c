#include "libft.h"

int	ft_strstr(char *s1, char *s2)
{
	int	i;
	int	j;

	i = 0;
	while (s1 && s1[i])
	{
		j = 0;
		while (s2 && s2[j])
		{
			if (s1[i] == s2[j])
				return (i);
			j++;
		}
		i++;
	}
	return (-1);
}
